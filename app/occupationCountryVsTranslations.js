// Copy for country-vs-country pages
// (/profile/occupation/[id]/country/[countryId]/vs/[otherId]).
//
// Same rule as the occupation × country templates: country names stay in
// the form the DB stores (nominative, no article), so every language
// except English uses label/colon constructions ("Duels remportés :
// France 6, Brésil 4") instead of sentences that would need an article or a
// grammatical case on the country name.
//
// Params (all pre-formatted strings unless noted):
//   A, B            country names; AThe/BThe add the English article
//   pair            "A vs B"
//   occPlural, occPluralTitle, occSingular
//   groupA, groupB  "{occupation} from {country}" phrases (buildNames().group)
//   nA, nB, rankA, rankB, totalCountries
//   topA, topB      each country's #1
//   W/L, WThe/LThe, nW, nL       more / fewer people
//   hiName, hiHpi, loName, loHpi the higher- and lower-ranked #1
//   wa, wb, wW, total            head-to-head wins (A, B, winner), matchups
//   k, ka, kb, KW, KWThe, kW     combined top-k split, its winner
//   X, XThe                      one country, for "compare X with…"

