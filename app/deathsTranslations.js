function interpolate(template, params = {}) {
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    params[key] === undefined || params[key] === null
      ? match
      : `${params[key]}`
  );
}

export function getDeathsTranslations(locale = DEFAULT_LOCALE) {
  const normalized = SUPPORTED_LOCALES.includes(locale)
    ? locale
    : DEFAULT_LOCALE;
  const local = messages[normalized] || messages[DEFAULT_LOCALE];
  return (key, params) => interpolate(
    local[key] ?? messages[DEFAULT_LOCALE][key] ?? key,
    params,
  );
}

export function getDeathsMessageKeys() {
  return Object.keys(messages[DEFAULT_LOCALE]);
}

export function getDeathsLocaleMessages(locale) {
  return messages[locale] || null;
}

export function formatDeathsNumber(value, locale = DEFAULT_LOCALE, options) {
  return new Intl.NumberFormat(locale, options).format(value);
}

export function formatDeathsYear(value, locale = DEFAULT_LOCALE) {
  return formatDeathsNumber(value, locale, {useGrouping: false});
}

export function formatDeathsDate(value, locale = DEFAULT_LOCALE) {
  if (!value) return "";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return new Intl.DateTimeFormat(locale, {
    day: "numeric",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  }).format(date);
}

export function formatDeathsMonthYear(
  year,
  monthIndex,
  locale = DEFAULT_LOCALE,
) {
  return new Intl.DateTimeFormat(locale, {
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(Date.UTC(Number(year), monthIndex, 1)));
}
